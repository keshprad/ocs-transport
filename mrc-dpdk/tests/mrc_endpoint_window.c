int main(void)
{
    const struct { const uint8_t *bytes; size_t length; } frames[] = {
        {write_frame, sizeof(write_frame)}, {trim_frame, sizeof(trim_frame)},
        {unknown_frame, sizeof(unknown_frame)},
    };
    for (unsigned int frame = 0; frame < 3; frame++) {
        struct mrc_wire_packet header;
        assert(mrc_wire_dispatch_header(frames[frame].bytes, frames[frame].length, &header) == 0);
        for (unsigned int edge = 0; edge < 3; edge++) {
            const int32_t offsets[] = {128, -1, -(int32_t)MRC_PSN_HALF};
            uint8_t slots[128], saved_slots[128];
            struct mrc_endpoint_config config = {
                .ip_version = MRC_WIRE_IP4, .responder_qpn = header.bth.dqp,
                .partition_key = header.bth.p_key, .peer_partition_key = header.bth.p_key,
                .local_ip = header.ipv4.dst_ip, .peer_ip = header.ipv4.src_ip,
                .udp_port = header.ipv4.dst_port, .trim_dscp = 47,
            };
            memcpy(config.paths[0].local.addr_bytes, header.ipv4.dst_mac, MRC_MAC_LEN);
            memcpy(config.paths[0].peer.addr_bytes, header.ipv4.src_mac, MRC_MAC_LEN);
            struct mrc_endpoint_counters counts = {0};
            struct mrc_responder receiver = {.transfer = &config, .counts = &counts,
                                             .last_frame = 1, .last_progress = 2};
            assert(mrc_rx_init(&receiver.qp, mrc_psn_add(header.bth.psn, -offsets[edge]), 128, slots));
            struct mrc_responder saved;
            memcpy(&saved, &receiver, sizeof(saved));
            memcpy(saved_slots, slots, sizeof(slots));
            struct rte_mbuf mbuf = {.buf_addr = (void *)frames[frame].bytes,
                .data_len = frames[frame].length, .pkt_len = frames[frame].length, .nb_segs = 1};
            struct mrc_endpoint_rx_packet packet = {.mbuf = &mbuf, .arrival_cycles = 99};
            assert(receive_frame(&config, &receiver, &counts, 0, &packet) == 0);
            assert(counts.rx[0].frames == 1 && counts.rx[0].matched == 1 && !counts.rx[0].rejected);
            assert(!counts.sacks && !counts.nack_sent_mask && !counts.trimmed && !counts.transport_acks);
            assert(memcmp(&receiver, &saved, sizeof(saved)) == 0);
            assert(memcmp(slots, saved_slots, sizeof(slots)) == 0);
        }
    }
    puts("Outside-window WRITE, trim and unsupported opcode preserve responder state and drain timer");
    return 0;
}
